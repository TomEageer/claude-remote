const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  setupRun: (input) => ipcRenderer.invoke('setup:run', input),
  setupAuthStart: () => ipcRenderer.invoke('setup:authStart'),
  setupAuthCode: (code) => ipcRenderer.invoke('setup:authCode', code),
  setupApiKey: (key) => ipcRenderer.invoke('setup:apiKey', key),
  setupCancel: () => ipcRenderer.invoke('setup:cancel'),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  onSetupLog: (cb) => ipcRenderer.on('setup:log', (_e, p) => cb(p)),
  loadData: () => ipcRenderer.invoke('data:load'),
  saveData: (data) => ipcRenderer.invoke('data:save', data),
  applySettings: (s) => ipcRenderer.invoke('settings:apply', s),
  connect: () => ipcRenderer.invoke('ssh:connect'),
  run: (args) => ipcRenderer.invoke('claude:run', args),
  stop: (sessionId) => ipcRenderer.invoke('claude:stop', sessionId),
  pickFiles: () => ipcRenderer.invoke('files:pick'),
  pickKey: () => ipcRenderer.invoke('files:pickKey'),
  upload: (uploadId, localPath) => ipcRenderer.invoke('files:upload', { uploadId, localPath }),
  listDir: (dir) => ipcRenderer.invoke('files:list', dir),
  download: (remotePath) => ipcRenderer.invoke('files:download', remotePath),
  pathForFile: (file) => webUtils.getPathForFile(file),
  mkdir: (dir, name) => ipcRenderer.invoke('files:mkdir', dir, name),
  rename: (p, name) => ipcRenderer.invoke('files:rename', p, name),
  remove: (p) => ipcRenderer.invoke('files:delete', p),
  uploadTo: (uploadId, localPath, dir) => ipcRenderer.invoke('files:uploadTo', { uploadId, localPath, dir }),
  downloadDir: (dir) => ipcRenderer.invoke('files:downloadDir', dir),
  previewFetch: (p) => ipcRenderer.invoke('preview:fetch', p),
  previewRead: (p) => ipcRenderer.invoke('preview:read', p),
  pluginsList: () => ipcRenderer.invoke('plugins:list'),
  pluginsStore: (url) => ipcRenderer.invoke('plugins:store', url),
  pluginsInstall: (item) => ipcRenderer.invoke('plugins:install', item),
  pluginsUninstall: (id) => ipcRenderer.invoke('plugins:uninstall', id),
  onPluginProgress: (cb) => ipcRenderer.on('plugins:progress', (_e, p) => cb(p)),
  capsGlobal: () => ipcRenderer.invoke('caps:global'),
  capsMcpStatus: () => ipcRenderer.invoke('caps:mcpStatus'),
  capsMcpAdd: (spec) => ipcRenderer.invoke('caps:mcpAdd', spec),
  capsMcpRemove: (name, scope) => ipcRenderer.invoke('caps:mcpRemove', name, scope),
  capsSkillAdd: () => ipcRenderer.invoke('caps:skillAdd'),
  capsSkillRemove: (dir) => ipcRenderer.invoke('caps:skillRemove', dir),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  appVersion: () => ipcRenderer.invoke('app:version'),
  onUpdate: (cb) => ipcRenderer.on('update:status', (_e, p) => cb(p)),
  onDlProgress: (cb) => ipcRenderer.on('files:dlprogress', (_e, p) => cb(p)),
  onState: (cb) => ipcRenderer.on('ssh:state', (_e, s) => cb(s)),
  onEvent: (cb) => ipcRenderer.on('claude:event', (_e, p) => cb(p)),
  onProgress: (cb) => ipcRenderer.on('files:progress', (_e, p) => cb(p)),
});
